#!/usr/bin/env python3
"""Generate language bindings from the takeover deployment manifest.
--check validates checked-in bindings without modifying them. No signing/install.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def generated_files():
    config = json.loads((ROOT / 'takeover-config.json').read_text())
    lines = ['// Generated by DriverKitProbe/generate-config.py; edit takeover-config.json.',
             'enum TakeoverConfiguration {']
    for key, value in config.items():
        kind = 'Int64' if key == 'pointerEventTag' else ('Int' if isinstance(value, int) else 'String')
        lines.append(f'    static let {key}: {kind} = {json.dumps(value)}')
    lines.append('}')
    header = ('// Generated by generate-config.py; edit takeover-config.json.\n'
              '#pragma once\n'
              f'constexpr unsigned AMTTakeoverBuild = {config["driverBuild"]};\n')
    return {ROOT.parent/'GlassToKey/GlassToKey/Runtime/TakeoverConfiguration.swift': '\n'.join(lines)+'\n',
            ROOT/'Driver/TakeoverConfiguration.h': header}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in generated_files().items():
        if not path.exists() or path.read_text() != content:
            if args.check: stale.append(str(path))
            else: path.write_text(content)
    if stale: parser.exit(1, 'Stale takeover configuration bindings: '+', '.join(stale)+'\n')

if __name__ == '__main__': main()
