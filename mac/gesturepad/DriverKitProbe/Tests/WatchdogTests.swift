import Foundation
@main
struct WatchdogTests {
    static func main() {
        let a = ReceiverWatchdog.Receiver(serial: "A", opened: true, handoffRequested: false)
        let b = ReceiverWatchdog.Receiver(serial: "B", opened: true, handoffRequested: false)
        let releasedA = ReceiverWatchdog.Receiver(serial: "A", opened: false, handoffRequested: true)
        var watchdog = ReceiverWatchdog()
        precondition(!watchdog.shouldRemove(after: [a,b]))
        precondition(!watchdog.shouldRemove(after: [releasedA,b]), "Deliberate close must preserve B")
        precondition(!watchdog.shouldRemove(after: [b]), "Deliberate termination must preserve B")
        precondition(watchdog.shouldRemove(after: []), "Unexpected loss of B must still recover")
        var single = ReceiverWatchdog()
        precondition(!single.shouldRemove(after: [a]), "One pad is valid")
        precondition(single.shouldRemove(after: []), "Unexpected single-pad loss must recover")
        var closed = ReceiverWatchdog()
        precondition(!closed.shouldRemove(after: [a,b]))
        precondition(closed.shouldRemove(after: [.init(serial: "A", opened: false, handoffRequested: false),b]))
        var reopened = ReceiverWatchdog()
        precondition(!reopened.shouldRemove(after: [a,b]))
        precondition(!reopened.shouldRemove(after: [releasedA,b]))
        precondition(!reopened.shouldRemove(after: [a,b]))
        precondition(reopened.shouldRemove(after: [b]), "Reopening reinstates loss protection")
        var zero = ReceiverWatchdog()
        precondition(!zero.shouldRemove(after: []))
        precondition(!zero.shouldRemove(after: [releasedA]))
        precondition(!zero.shouldRemove(after: []), "Zero owned pads after deliberate handoff is valid")
        var reconnect = ReceiverWatchdog()
        precondition(!reconnect.shouldRemove(after: [a,b], physicallyConnected: ["A","B"]))
        precondition(!reconnect.shouldRemove(after: [b], physicallyConnected: ["B"]), "Physical disconnect preserves B")
        precondition(!reconnect.shouldRemove(after: [b], physicallyConnected: ["A","B"]), "Wait for matching on reconnect")
        precondition(!reconnect.shouldRemove(after: [a,b], physicallyConnected: ["A","B"]))
        precondition(reconnect.shouldRemove(after: [b], physicallyConnected: ["A","B"]), "A subsequent crash while connected still recovers")
        var allDisconnected = ReceiverWatchdog()
        precondition(!allDisconnected.shouldRemove(after: [a,b], physicallyConnected: ["A","B"]))
        precondition(!allDisconnected.shouldRemove(after: [], physicallyConnected: []), "No hardware left to strand")
        var closingDisconnect = ReceiverWatchdog()
        precondition(!closingDisconnect.shouldRemove(after: [a,b], physicallyConnected: ["A","B"]))
        precondition(!closingDisconnect.shouldRemove(after: [.init(serial: "A", opened: false, handoffRequested: false),b], physicallyConnected: ["B"]))
        print("Receiver watchdog lifecycle tests passed")
    }
}
